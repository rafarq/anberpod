"""Internationalization foundation: supported locales, translation bundle,
system-language detection and lookup helper.

Structurally mirrors the sibling ``rg35xxh-radio`` project's
``radio/i18n.py`` (same 15 supported locales, same public API shape).
Nothing here touches rendering or input handling; :mod:`anberpod.app` and
:mod:`anberpod.ui.state` only store the *active* language code and ask this
module to translate keys — they never hardcode strings or know how
detection/fallback works internally.

Language resolution order:

1. A valid ``language`` value already persisted via
   :class:`anberpod.domain.ports.SettingsRepository` wins outright.
2. Otherwise, detect the system language from the standard POSIX locale
   environment variables (``LC_ALL`` > ``LC_MESSAGES`` > ``LANG``, the usual
   glibc precedence) or, failing that, :func:`locale.getlocale`.
3. If nothing detected maps to a supported locale, default to English.
"""

